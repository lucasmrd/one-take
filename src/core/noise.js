// Star field on the sky sphere, shared by space-like skies.
export const STARS_GLSL = /* glsl */ `
vec3 starLayer(vec3 d, float scale, float density, float size){
  vec3 p = d*scale;
  vec3 c = floor(p);
  vec3 f = fract(p);
  float h = hash13(c);
  if (h > density) return vec3(0.0);
  vec3 o = hash33(c + 7.1)*0.6 + 0.2;
  float dist = length(f - o);
  float b = exp(-dist*dist/(size*size));
  float t = hash13(c + 3.7);
  vec3 tint = mix(vec3(0.75, 0.82, 1.0), vec3(1.0, 0.85, 0.65), t);
  return tint*b*(0.4 + 2.6*pow(hash13(c + 1.3), 6.0));
}
vec3 stars(vec3 d){
  return starLayer(d, 90.0, 0.10, 0.07) + starLayer(d, 210.0, 0.16, 0.08)*0.7 + starLayer(d, 420.0, 0.2, 0.09)*0.45;
}
`;
